const dictionaries: Record<Locale, Record<MessageKey, string>> = { zh, en };

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[parseLocale(locale)][key] || zh[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

const API_ERROR_KEYS: Record<string, MessageKey> = {
  未登录: "payNeedLogin",
  请先登录: "payNeedLogin",
  保存失败: "saveFailed",
  操作失败: "errorGeneric",
  结算失败: "checkoutFailed",
  请先选择要购买的课程: "pickCourse",
  无法验证: "verifyFailed",
  两次密码不一致: "authPasswordMismatch",
};

export function translateApiError(locale: Locale, error?: string, fallback: MessageKey = "errorGeneric"): string {
  if (!error) return t(locale, fallback);
  const key = API_ERROR_KEYS[error];
  if (key) return t(locale, key);
  const matched = (Object.keys(zh) as MessageKey[]).find((item) => zh[item] === error);
  if (matched) return t(locale, matched);
  return error;
}

